    private void btnCreateAccountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateAccountActionPerformed
        // TODO add your handling code here:
        String name = txtName.getText();
    String nic = txtNIC.getText();
    String phone = txtPhone.getText();

    if (name.isEmpty() || nic.isEmpty() || phone.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Fill all fields except Account No");
        return;
    }

    if (!phone.matches("\\d{10}")) {
        JOptionPane.showMessageDialog(this, "Phone must be 10 digits");
        return;
    }

    double balance;
    try {
        balance = Double.parseDouble(txtBalance.getText());

        if (balance < 0) {
            JOptionPane.showMessageDialog(this, "Invalid Balance");
            return;
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Enter valid balance");
        return;
    }

    // ✅ AUTO ACCOUNT NUMBER (IMPORTANT FIX)
    String accNo = bank.generateNextAccountNo();  
    txtAccNo.setText(accNo);

    String res = bank.createAccount(accNo, name, nic, phone, balance);
    JOptionPane.showMessageDialog(this, res);

    refreshTable();

    txtAccNo.setText("");
    txtName.setText("");
    txtNIC.setText("");
    txtPhone.setText("");
    txtBalance.setText("");

    }//GEN-LAST:event_btnCreateAccountActionPerformed

