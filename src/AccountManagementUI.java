   private void refreshTable() {

    model.setRowCount(0);

    for (Account a : bank.getAllAccounts()) {

        model.addRow(new Object[]{
            a.accNo,
            a.name,
            a.nic,
            a.phone,
            a.balance,
            a.active ? "ACTIVE" : "DEACTIVE"
        });
    }

    jTable1.clearSelection();
    btnToggleStatus.setEnabled(false);

}
