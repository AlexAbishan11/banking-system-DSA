    private void btnWithdrawActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnWithdrawActionPerformed
        // TODO add your handling code here:
         String acc = txtAcc.getText();
    if(acc.isEmpty()){
        JOptionPane.showMessageDialog(this, "Enter Account No");
        return;
    }
    
    double amount;
    try{
        amount = Double.parseDouble(txtAmount.getText());
        if(amount <= 0){
            JOptionPane.showMessageDialog(this, "Amount must be > 0");
            return;
        }
    }catch(Exception e){
        JOptionPane.showMessageDialog(this, "Invalid Amount");
        return;
    }
    
    
    int vipOption = JOptionPane.showConfirmDialog(this, 
        "Is this a VIP Priority transaction?", "VIP Priority", 
        JOptionPane.YES_NO_OPTION);
    boolean isVIP = (vipOption == JOptionPane.YES_OPTION);
    
    
    String res = bank.withdraw(acc, amount, isVIP);  // ← WITHDRAW (Correct)
    JOptionPane.showMessageDialog(this, res);
    
    
    JOptionPane.showMessageDialog(this, bank.viewQueue());
    
   
    int processNow = JOptionPane.showConfirmDialog(this, 
        "Process next transaction in queue?", "Process Queue", 
        JOptionPane.YES_NO_OPTION);
    
    if (processNow == JOptionPane.YES_OPTION) {
        String result = bank.processNextTransaction();
        JOptionPane.showMessageDialog(this, result);
    }
    
    refreshTable();
    txtAmount.setText("");
    }//GEN-LAST:event_btnWithdrawActionPerformed

